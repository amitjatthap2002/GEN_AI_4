# 2. Common Setup (Seed configuration and output path definition)
from pathlib import Path
import random
import torch
import matplotlib.pyplot as plt

SEED = 42
random.seed(SEED)
torch.manual_seed(SEED)
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
out = Path("lab_outputs")
out.mkdir(exist_ok=True)
print("Device configured:", device)

# 3. Step 1: Load Stable Diffusion v1-5 Pipeline
from diffusers import StableDiffusionPipeline
from IPython.display import display
import torch

repo = "stable-diffusion-v1-5/stable-diffusion-v1-5"

# Configure precision depending on device availability
if device.type == "cuda":
    print("Loading Stable Diffusion on CUDA GPU (float16)... ")
    pipe = StableDiffusionPipeline.from_pretrained(repo, torch_dtype=torch.float16)
    pipe = pipe.to(device)
    pipe.enable_attention_slicing()
else:
    print("Loading Stable Diffusion on CPU (float32, this may take a few minutes)... ")
    pipe = StableDiffusionPipeline.from_pretrained(repo, torch_dtype=torch.float32)
    pipe = pipe.to(device)

print("Stable Diffusion Pipeline loaded successfully.")

# 4. Step 2: Compare Prompt Variants & Generate Images
prompts = [
    "A small library with a reading table, wide view, watercolor illustration",
    "A small library with a reading table, wide view, pencil sketch",
]

for i, prompt in enumerate(prompts, 1):
    for seed in (42, 43):
        print(f"Generating: Prompt {i}, Seed: {seed}...")
        rng = torch.Generator(device=device).manual_seed(seed)

        # Use fewer steps on CPU to speed up execution if needed, standard is 25
        steps = 25 if device.type == "cuda" else 12
        result = pipe(prompt, width=512, height=512,
                      num_inference_steps=steps, guidance_scale=7.5, generator=rng)

        # Check for safety filter
        flags = result.nsfw_content_detected
        if flags and flags[0]:
            print("Image flagged. Review the classroom prompt.")
            continue

        image = result.images[0]
        image.save(out / f"library_prompt_{i}_seed_{seed}.png")
        display(image)

